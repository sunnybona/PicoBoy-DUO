#!/usr/bin/env python3
"""把多个 .gb ROM 转成一组 C 数组 + 一张选择表（构建时生成，数组放 flash 由 XIP 直读）。

用法: make_roms_c.py <manifest.txt> <out.c>

manifest.txt 每行一条:  <显示用的名字>|<rom 路径>
（不走命令行传路径，是因为 Windows 上带空格/括号的路径经过 ninja 命令行
 很容易被拆错；用一个清单文件最稳。）
"""
import sys
import os

def main():
    manifest_path = sys.argv[1]
    dst = sys.argv[2]

    entries = []
    if os.path.exists(manifest_path):
        with open(manifest_path, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line or line.startswith("#"):
                    continue
                if "|" not in line:
                    continue
                name, path = line.split("|", 1)
                path = path.strip()
                if not os.path.exists(path):
                    print("skip (missing): %s" % path)
                    continue
                with open(path, "rb") as rf:
                    data = rf.read()
                if len(data) < 0x8000:
                    print("skip (too small): %s" % path)
                    continue
                entries.append((name.strip(), data))
                print("embed: %-16s %8d bytes  %s" % (name.strip(), len(data), path))

    out = []
    out.append("/* auto-generated by tools/make_roms_c.py —— 不要手改 */\n")
    out.append("#include <stdint.h>\n")
    out.append('#include "rom_table.h"\n\n')

    if not entries:
        out.append("const uint8_t gb_rom_dummy[1] __attribute__((aligned(4))) = {0};\n")
        out.append("const gb_rom_entry_t gb_roms[1] = { { \"NO ROM\", gb_rom_dummy, 0u } };\n")
        out.append("const unsigned int gb_rom_count = 0u;\n")
    else:
        for i, (name, data) in enumerate(entries):
            out.append("const uint8_t gb_rom_%d[%d] __attribute__((aligned(4))) = {\n"
                       % (i, len(data)))
            for k in range(0, len(data), 16):
                chunk = data[k:k + 16]
                out.append("    " + "".join("0x%02x," % b for b in chunk) + "\n")
            out.append("};\n\n")

        out.append("const gb_rom_entry_t gb_roms[%d] = {\n" % len(entries))
        for i, (name, data) in enumerate(entries):
            esc = name.replace("\\", "\\\\").replace('"', '\\"')
            out.append('    { "%s", gb_rom_%d, %du },\n' % (esc, i, len(data)))
        out.append("};\n")
        out.append("const unsigned int gb_rom_count = %du;\n\n" % len(entries))

        # 兼容旧单 ROM 目标（rp2040_gb_cpp / 根目录 main.cpp）：指向第一个 ROM
        out.append("/* compat：单 ROM 目标用 */\n")
        out.append("const uint8_t *gb_rom_data = gb_rom_0;\n")
        out.append("const uint32_t gb_rom_size = %du;\n" % len(entries[0][1]))

    with open(dst, "w", newline="\n", encoding="utf-8") as f:
        f.write("".join(out))


if __name__ == "__main__":
    main()
