/* 3x5 点阵，每行 3 位（bit2..bit0），5 行一个字符。
 * 只覆盖 0-9 A-Z 和少量符号，够打印状态信息。 */
#ifndef FONT3X5_H
#define FONT3X5_H

#include <stdint.h>
#include <string.h>

static const uint8_t FONT3X5_DIGITS[10][5] = {
    {0x7, 0x5, 0x5, 0x5, 0x7}, /* 0 */
    {0x2, 0x2, 0x2, 0x2, 0x7}, /* 1 */
    {0x6, 0x1, 0x3, 0x4, 0x7}, /* 2 */
    {0x7, 0x1, 0x3, 0x1, 0x7}, /* 3 */
    {0x5, 0x5, 0x7, 0x1, 0x1}, /* 4 */
    {0x7, 0x4, 0x7, 0x1, 0x7}, /* 5 */
    {0x3, 0x4, 0x7, 0x5, 0x3}, /* 6 */
    {0x7, 0x1, 0x1, 0x1, 0x1}, /* 7 */
    {0x7, 0x5, 0x7, 0x5, 0x7}, /* 8 */
    {0x7, 0x5, 0x7, 0x1, 0x3}, /* 9 */
};

static const uint8_t FONT3X5_ALPHA[26][5] = {
    {0x2, 0x5, 0x7, 0x5, 0x5}, /* A */
    {0x6, 0x5, 0x6, 0x5, 0x6}, /* B */
    {0x3, 0x4, 0x4, 0x4, 0x3}, /* C */
    {0x6, 0x5, 0x5, 0x5, 0x6}, /* D */
    {0x7, 0x4, 0x6, 0x4, 0x7}, /* E */
    {0x7, 0x4, 0x6, 0x4, 0x4}, /* F */
    {0x3, 0x4, 0x5, 0x5, 0x3}, /* G */
    {0x5, 0x5, 0x7, 0x5, 0x5}, /* H */
    {0x7, 0x2, 0x2, 0x2, 0x7}, /* I */
    {0x1, 0x1, 0x1, 0x5, 0x2}, /* J */
    {0x5, 0x5, 0x6, 0x4, 0x3}, /* K */
    {0x4, 0x4, 0x4, 0x4, 0x7}, /* L */
    {0x5, 0x7, 0x5, 0x5, 0x5}, /* M */
    {0x5, 0x6, 0x5, 0x5, 0x4}, /* N */
    {0x2, 0x5, 0x5, 0x5, 0x2}, /* O */
    {0x7, 0x5, 0x7, 0x4, 0x4}, /* P */
    {0x2, 0x5, 0x5, 0x5, 0x3}, /* Q */
    {0x6, 0x5, 0x6, 0x5, 0x5}, /* R */
    {0x3, 0x4, 0x3, 0x1, 0x3}, /* S */
    {0x7, 0x2, 0x2, 0x2, 0x2}, /* T */
    {0x5, 0x5, 0x5, 0x5, 0x6}, /* U */
    {0x5, 0x5, 0x5, 0x5, 0x2}, /* V */
    {0x5, 0x5, 0x5, 0x7, 0x2}, /* W */
    {0x5, 0x5, 0x2, 0x5, 0x5}, /* X */
    {0x5, 0x5, 0x2, 0x2, 0x2}, /* Y */
    {0x7, 0x1, 0x2, 0x4, 0x7}, /* Z */
};

/* 标点：'.' ':' '-' '/' '_' '?' '!' '+' 空格 */
#define FONT3X5_PUNCT_COUNT 9
static const uint8_t FONT3X5_PUNCT[FONT3X5_PUNCT_COUNT][5] = {
    {0x0, 0x0, 0x0, 0x0, 0x2}, /* . */
    {0x0, 0x2, 0x0, 0x2, 0x0}, /* : */
    {0x0, 0x0, 0x7, 0x0, 0x0}, /* - */
    {0x1, 0x1, 0x2, 0x4, 0x4}, /* / */
    {0x0, 0x0, 0x0, 0x0, 0x7}, /* _ */
    {0x7, 0x1, 0x2, 0x0, 0x2}, /* ? */
    {0x2, 0x2, 0x2, 0x0, 0x2}, /* ! */
    {0x0, 0x2, 0x7, 0x2, 0x0}, /* + */
    {0x0, 0x0, 0x0, 0x0, 0x0}, /* space */
};

/* 取字形；返回 NULL 表示不支持的字符（按空格处理）。 */
static inline const uint8_t *font3x5_glyph(char c)
{
    if(c >= '0' && c <= '9')
        return FONT3X5_DIGITS[c - '0'];
    if(c >= 'A' && c <= 'Z')
        return FONT3X5_ALPHA[c - 'A'];
    if(c >= 'a' && c <= 'z')
        return FONT3X5_ALPHA[c - 'a'];
    switch(c)
    {
    case '.': return FONT3X5_PUNCT[0];
    case ':': return FONT3X5_PUNCT[1];
    case '-': return FONT3X5_PUNCT[2];
    case '/': return FONT3X5_PUNCT[3];
    case '_': return FONT3X5_PUNCT[4];
    case '?': return FONT3X5_PUNCT[5];
    case '!': return FONT3X5_PUNCT[6];
    case '+': return FONT3X5_PUNCT[7];
    default:  return FONT3X5_PUNCT[8];
    }
}

#endif /* FONT3X5_H */
